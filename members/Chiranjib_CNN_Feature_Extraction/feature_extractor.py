import torch
import torch.nn as nn
from torchvision import models
from torchvision.models.feature_extraction import create_feature_extractor


class FeatureMaps:
    def __init__(self, features: dict):
        if not isinstance(features, dict) or len(features) == 0:
            raise ValueError("features must be a non-empty dictionary of tensors.")
        self.features = features

    def get_feature(self, name: str) -> torch.Tensor:
        if name not in self.features:
            raise ValueError(
                f"Feature map '{name}' not found. Available: {list(self.features.keys())}"
            )
        return self.features[name]

    def get_all_features(self) -> dict:
        return self.features

    def get_channel_dims(self) -> dict:
        return {name: feat.shape[1] for name, feat in self.features.items()}

    def to(self, device):
        self.features = {
            name: feat.to(device) for name, feat in self.features.items()
        }
        return self

    def display_shapes(self):
        print("Stored Multi-Scale Feature Maps:")
        for name, feature in self.features.items():
            print(
                f"  {name} -> Shape (B, C, H, W): {tuple(feature.shape)} | Device: {feature.device}"
            )


def build_backbone(arch="resnet34", pretrained=True, trainable=True):
    if arch == "resnet18":
        weights = models.ResNet18_Weights.DEFAULT if pretrained else None
        base_model = models.resnet18(weights=weights)
    elif arch == "resnet34":
        weights = models.ResNet34_Weights.DEFAULT if pretrained else None
        base_model = models.resnet34(weights=weights)
    elif arch == "resnet50":
        weights = models.ResNet50_Weights.DEFAULT if pretrained else None
        base_model = models.resnet50(weights=weights)
    else:
        raise ValueError(f"Unsupported architecture: {arch}")

    for param in base_model.parameters():
        param.requires_grad = trainable

    return_nodes = {
        "layer1": "C2",
        "layer2": "C3",
        "layer3": "C4",
        "layer4": "C5",
    }

    return create_feature_extractor(base_model, return_nodes=return_nodes)

class FeatureExtractor(nn.Module):
    """
    End-to-end CNN Feature Extractor module.
    Takes preprocessed image batches (B, 3, H, W) and outputs a FeatureMaps object
    containing hierarchical feature representations (C2, C3, C4, C5).
    """

    def __init__(self, arch="resnet34", pretrained=True, trainable=True):
        super().__init__()
        self.arch = arch
        self.backbone = build_backbone(
            arch=arch, pretrained=pretrained, trainable=trainable
        )

    def forward(self, images: torch.Tensor) -> FeatureMaps:
        if images.ndim != 4 or images.shape[1] != 3:
            raise ValueError(
                f"Expected input tensor of shape (B, 3, H, W), got {tuple(images.shape)}"
            )
        raw_features = self.backbone(images)
        return FeatureMaps(raw_features)

if __name__ == "__main__":
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    extractor = FeatureExtractor(
        arch="resnet34",
        pretrained=True,
        trainable=True,
    ).to(device)

    batch_images = torch.randn(2, 3, 512, 512, device=device)
    feature_maps = extractor(batch_images)
    feature_maps.display_shapes()
    print("\nOutput Channel Dimensions:", feature_maps.get_channel_dims())

    loss = sum(feat.mean() for feat in feature_maps.get_all_features().values())
    loss.backward()

    first_layer_grad = extractor.backbone.conv1.weight.grad
    print("Backpropagation check passed:", first_layer_grad is not None)
    print("conv1 gradient norm:", round(first_layer_grad.norm().item(), 6))