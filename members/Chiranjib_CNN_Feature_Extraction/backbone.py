def build_backbone(arch="resnet34", pretrained=True, trainable=True):
    """
    Builds a pretrained ResNet feature extraction backbone returning
    multi-scale feature maps C2, C3, C4, and C5.
    """
    if arch == "resnet18":
        weights = models.ResNet18_Weights.DEFAULT if pretrained else None
        base_model = models.resnet18(weights=weights)
    elif arch == "resnet34":
        weights = models.ResNet34_Weights.DEFAULT if pretrained else None
        base_model = models.resnet34(weights=weights)
    elif arch == "resnet50":
        weights = models.ResNet50_Weights.DEFAULT if pretrained else None
        base_model = models.resnet50(weights=weights)
    else:
        raise ValueError(f"Unsupported architecture: {arch}")

    # Set parameter trainability for fine-tuning
    for param in base_model.parameters():
        param.requires_grad = trainable

    # Map ResNet stages to standard multi-scale pyramid levels
    return_nodes = {
        "layer1": "C2",  # Stride 4  -> 128x128 for 512x512 input
        "layer2": "C3",  # Stride 8  -> 64x64
        "layer3": "C4",  # Stride 16 -> 32x32
        "layer4": "C5",  # Stride 32 -> 16x16
    }

    backbone = create_feature_extractor(base_model, return_nodes=return_nodes)
    return backbone

if __name__ == "__main__":
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    backbone = build_backbone(
        arch="resnet34",
        pretrained=True,
        trainable=True,
    ).to(device)

    dummy_input = torch.randn(2, 3, 512, 512, device=device)
    outputs = backbone(dummy_input)

    print("\nExtracted Feature Map Shapes:")
    for level, tensor in outputs.items():
        print(f"  {level}: {tuple(tensor.shape)}")

    total_params = sum(p.numel() for p in backbone.parameters())
    trainable_params = sum(
        p.numel() for p in backbone.parameters() if p.requires_grad
    )
    print(f"Total Parameters:     {total_params:,}")
    print(f"Trainable Parameters: {trainable_params:,}")