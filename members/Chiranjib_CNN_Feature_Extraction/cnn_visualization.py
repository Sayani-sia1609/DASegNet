import urllib.request
import cv2
import matplotlib.pyplot as plt
import numpy as np
import torch
import torch.nn as nn
from torchvision import models, transforms
from torchvision.models.feature_extraction import create_feature_extractor


class FeatureMaps:
    def __init__(self, features: dict):
        if not isinstance(features, dict) or len(features) == 0:
            raise ValueError("features must be a non-empty dictionary of tensors.")
        self.features = features

    def get_feature(self, name: str) -> torch.Tensor:
        if name not in self.features:
            raise ValueError(
                f"Feature map '{name}' not found. Available: {list(self.features.keys())}"
            )
        return self.features[name]

    def get_all_features(self) -> dict:
        return self.features


def build_backbone(arch="resnet34", pretrained=True, trainable=True):
    if arch == "resnet18":
        weights = models.ResNet18_Weights.DEFAULT if pretrained else None
        base_model = models.resnet18(weights=weights)
    elif arch == "resnet34":
        weights = models.ResNet34_Weights.DEFAULT if pretrained else None
        base_model = models.resnet34(weights=weights)
    elif arch == "resnet50":
        weights = models.ResNet50_Weights.DEFAULT if pretrained else None
        base_model = models.resnet50(weights=weights)
    else:
        raise ValueError(f"Unsupported architecture: {arch}")

    for param in base_model.parameters():
        param.requires_grad = trainable

    return_nodes = {
        "layer1": "C2",
        "layer2": "C3",
        "layer3": "C4",
        "layer4": "C5",
    }
    return create_feature_extractor(base_model, return_nodes=return_nodes)


class FeatureExtractor(nn.Module):
    def __init__(self, arch="resnet34", pretrained=True, trainable=True):
        super().__init__()
        self.backbone = build_backbone(
            arch=arch, pretrained=pretrained, trainable=trainable
        )

    def forward(self, images: torch.Tensor) -> FeatureMaps:
        return FeatureMaps(self.backbone(images))

def visualize_feature_maps(
    features: FeatureMaps,
    layer: str = "C2",
    num_channels: int = 8,
    save_path: str = None,
):
    """
    Plots the first `num_channels` activation maps for a given ResNet stage (C2-C5).
    """
    feature_map = features.get_feature(layer)[0].detach().cpu()
    num_channels = min(num_channels, feature_map.shape[0])
    rows = (num_channels + 3) // 4

    plt.figure(figsize=(12, 3 * rows))
    for i in range(num_channels):
        plt.subplot(rows, 4, i + 1)
        channel = feature_map[i, :, :].numpy()
        plt.imshow(channel, cmap="viridis")
        plt.title(f"Channel {i + 1}")
        plt.axis("off")

    plt.suptitle(f"CNN Feature Maps - {layer} {tuple(feature_map.shape)}", fontsize=13)
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, bbox_inches="tight", dpi=150)
    plt.show()


def compare_degraded_features(
    clean_img_rgb: np.ndarray,
    degraded_img_rgb: np.ndarray,
    clean_features: FeatureMaps,
    degraded_features: FeatureMaps,
    save_path: str = None,
):
    """
    Side-by-side comparison of Clean vs. Degraded inputs and their mean C2 (low-level)
    and C5 (high-level semantic) feature activations, plus feature drift metrics.
    """
    clean_c2 = clean_features.get_feature("C2")[0].detach().cpu()
    deg_c2 = degraded_features.get_feature("C2")[0].detach().cpu()

    clean_c5 = clean_features.get_feature("C5")[0].detach().cpu()
    deg_c5 = degraded_features.get_feature("C5")[0].detach().cpu()

    # Quantify feature distortion using L2 relative error
    c2_drift = torch.norm(clean_c2 - deg_c2) / torch.norm(clean_c2)
    c5_drift = torch.norm(clean_c5 - deg_c5) / torch.norm(clean_c5)

    fig, axes = plt.subplots(2, 3, figsize=(15, 9))

    axes[0, 0].imshow(clean_img_rgb)
    axes[0, 0].set_title("Clean Input Image (512x512)")
    axes[0, 0].axis("off")

    axes[0, 1].imshow(clean_c2.mean(dim=0), cmap="viridis")
    axes[0, 1].set_title("Clean C2 Mean Activation (Edges/Textures)")
    axes[0, 1].axis("off")

    axes[0, 2].imshow(clean_c5.mean(dim=0), cmap="viridis")
    axes[0, 2].set_title("Clean C5 Mean Activation (High-Level Semantics)")
    axes[0, 2].axis("off")

    axes[1, 0].imshow(degraded_img_rgb)
    axes[1, 0].set_title("Degraded Input (Blur + Noise + JPEG)")
    axes[1, 0].axis("off")

    axes[1, 1].imshow(deg_c2.mean(dim=0), cmap="viridis")
    axes[1, 1].set_title(f"Degraded C2 (Relative Drift: {c2_drift:.2%})")
    axes[1, 1].axis("off")

    axes[1, 2].imshow(deg_c5.mean(dim=0), cmap="viridis")
    axes[1, 2].set_title(f"Degraded C5 (Relative Drift: {c5_drift:.2%})")
    axes[1, 2].axis("off")

    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, bbox_inches="tight", dpi=150)
    plt.show()

    return {"C2_relative_drift": round(c2_drift.item(), 4), "C5_relative_drift": round(c5_drift.item(), 4)}

