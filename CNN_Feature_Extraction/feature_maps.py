import torch


class FeatureMaps:
    """
    Container class for managing multi-scale CNN feature maps (C2, C3, C4, C5)
    and providing clean access, shape inspection, and device movement.
    """

    def __init__(self, features: dict):
        if not isinstance(features, dict) or len(features) == 0:
            raise ValueError("features must be a non-empty dictionary of tensors.")
        self.features = features

    def get_feature(self, name: str) -> torch.Tensor:
        if name not in self.features:
            raise ValueError(
                f"Feature map '{name}' not found. Available: {list(self.features.keys())}"
            )
        return self.features[name]

    def get_all_features(self) -> dict:
        return self.features

    def get_channel_dims(self) -> dict:
        """Returns a dictionary mapping each feature level to its channel count."""
        return {name: feat.shape[1] for name, feat in self.features.items()}

    def to(self, device):
        """Moves all stored feature tensors to the target device (cpu/cuda)."""
        self.features = {
            name: feat.to(device) for name, feat in self.features.items()
        }
        return self

    def display_shapes(self):
        print("Stored Multi-Scale Feature Maps:")
        for name, feature in self.features.items():
            print(
                f"  {name} -> Shape (B, C, H, W): {tuple(feature.shape)} | Device: {feature.device}"
            )

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# Simulate extracted ResNet-34 tensors for a batch of 2 images (512x512 input)
sample_dict = {
    "C2": torch.randn(2, 64, 128, 128, device=device),
    "C3": torch.randn(2, 128, 64, 64, device=device),
    "C4": torch.randn(2, 256, 32, 32, device=device),
    "C5": torch.randn(2, 512, 16, 16, device=device),
}

fm = FeatureMaps(sample_dict)

# 1. Inspect shapes and devices
fm.display_shapes()

# 2. Inspect channel dimensions dictionary (useful for Debasmita & Sayani)
print("\nChannel Dimensions Dictionary:", fm.get_channel_dims())

# 3. Retrieve a single level
c3_tensor = fm.get_feature("C3")
print("Retrieved C3 tensor shape:", tuple(c3_tensor.shape))